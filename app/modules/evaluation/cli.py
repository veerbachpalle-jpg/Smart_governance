async def run_cli(
    provider: str,
    dataset: str,
    min_safety_recall: float,
    compare: bool,
) -> None:
    reports_dir = Path("reports")
    reports_dir.mkdir(parents=True, exist_ok=True)
    timestamp_str = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")

    if compare or provider == "both":
        print("Running comparative evaluation on both Mock and Gemini providers...")
        async with async_session_factory() as session:
            mock_runner = EvaluationRunner(
                session=session,
                dataset_path=dataset,
                provider_type="mock",
                min_safety_recall=min_safety_recall,
            )
            mock_summary = await mock_runner.run_evaluation()

        async with async_session_factory() as session:
            gemini_runner = EvaluationRunner(
                session=session,
                dataset_path=dataset,
                provider_type="gemini",
                min_safety_recall=min_safety_recall,
            )
            gemini_summary = await gemini_runner.run_evaluation()

        # Write unified comparative report
        cmp_json = {
            "comparison_timestamp": datetime.now(timezone.utc).isoformat(),
            "mock": mock_summary,
            "gemini": gemini_summary,
        }
        cmp_json_path = reports_dir / f"eval_comparison_{timestamp_str}.json"
        with open(cmp_json_path, "w", encoding="utf-8") as f:
            json.dump(cmp_json, f, indent=2, ensure_ascii=False)

        cmp_md = render_comparison_markdown(mock_summary, gemini_summary, min_safety_recall)
        cmp_md_path = reports_dir / f"eval_comparison_{timestamp_str}.md"
        with open(cmp_md_path, "w", encoding="utf-8") as f:
            f.write(cmp_md)

        print(f"\nComparative evaluation reports written to {cmp_json_path} and {cmp_md_path}")
        print("\n=== Evaluation Summary (Mock Provider) ===")
        print(f"Safety-Critical Recall: {mock_summary['safety_critical_recall'] * 100:.2f}%")
        print(f"Language Accuracy:     {mock_summary['language_detection_accuracy'] * 100:.2f}%")
        print(f"Category Accuracy:     {mock_summary['category_accuracy'] * 100:.2f}%")
        print(f"Routing Top-1:         {mock_summary['routing_top_1'] * 100:.2f}%")
        print(f"Routing Top-3:         {mock_summary['routing_top_3'] * 100:.2f}%")
        print(f"Duplicate Precision@3: {mock_summary['duplicate_precision_at_k'] * 100:.2f}%")
        print(f"Abstention Rate:       {mock_summary['abstention_rate'] * 100:.2f}%")
    else:
        print(f"Running evaluation with provider '{provider}'...")
        async with async_session_factory() as session:
            runner = EvaluationRunner(
                session=session,
                dataset_path=dataset,
                provider_type=provider,
                min_safety_recall=min_safety_recall,
            )
            summary = await runner.run_evaluation()

        print(f"\nEvaluation report written to reports/eval_{timestamp_str}.json and .md")
        print(f"\n=== Evaluation Summary ({provider}) ===")
        print(f"Safety-Critical Recall: {summary['safety_critical_recall'] * 100:.2f}%")
        print(f"Language Accuracy:     {summary['language_detection_accuracy'] * 100:.2f}%")
        print(f"Category Accuracy:     {summary['category_accuracy'] * 100:.2f}%")
        print(f"Routing Top-1:         {summary['routing_top_1'] * 100:.2f}%")
        print(f"Routing Top-3:         {summary['routing_top_3'] * 100:.2f}%")
        print(f"Duplicate Precision@3: {summary['duplicate_precision_at_k'] * 100:.2f}%")
        print(f"Abstention Rate:       {summary['abstention_rate'] * 100:.2f}%")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Municipal Grievance Intelligence Evaluation Harness CLI"
    )
    parser.add_argument(
        "--provider",
        type=str,
        default="mock",
        choices=["mock", "gemini", "both"],
        help="Model provider to evaluate ('mock', 'gemini', or 'both')",
    )
    parser.add_argument(
        "--dataset",
        type=str,
        default="data/eval/dataset_v1.jsonl",
        help="Path to evaluation dataset JSONL file",
    )
    parser.add_argument(
        "--min-safety-recall",
        type=float,
        default=float(os.getenv("EVAL_MIN_SAFETY_RECALL", "0.95")),
        help="Minimum safety-critical recall threshold for CI validation (default: 0.95)",
    )
    parser.add_argument(
        "--compare",
        action="store_true",
        help="Run comparison between Mock and Gemini providers in a unified report",
    )

    args = parser.parse_args()

    try:
        asyncio.run(
            run_cli(
                provider=args.provider,
                dataset=args.dataset,
                min_safety_recall=args.min_safety_recall,
                compare=args.compare,
            )
        )
    except AssertionError as exc:
        print(f"\n[FAILED] Evaluation validation failed: {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:
        print(f"\n[ERROR] Error during evaluation: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
